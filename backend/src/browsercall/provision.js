// One SIP extension per TeamLink login, created on demand (backend runs as root on the VPS, so it writes the PJSIP include file and reloads res_pjsip).
// The password lives encrypted in the DB, is replaced every time a softphone session starts, and goes to the browser only inside that session's response.
const crypto = require('crypto');
const fs = require('fs');
const { execFile } = require('child_process');
const S = require('./schema');
const { ENV } = require('./config');
const { encryptSecret, decryptSecret } = require('../utils/secrets');

const newSecret = () => crypto.randomBytes(18).toString('base64url');

function render(rows) {
  const out = ['; GENERATED by TeamLink backend/src/browsercall/provision.js - do not edit by hand (browser calling extensions)'];
  for (const r of rows) {
    const secret = decryptSecret(r.secretEnc);
    if (!secret || !r.active) continue;
    out.push(`[${r.extension}](webrtc-tpl)\nauth=${r.extension}\naors=${r.extension}\ncallerid="TL ${r.extension}" <${r.extension}>\n[${r.extension}]\ntype=auth\nauth_type=userpass\nusername=${r.extension}\npassword=${secret}\n[${r.extension}]\ntype=aor\nmax_contacts=1\nremove_existing=yes\nremove_unavailable=yes\nqualify_frequency=0`);
  }
  return `${out.join('\n')}\n`;
}
const reload = () => new Promise((resolve, reject) => execFile(ENV.reloadCmd, ['-rx', 'module reload res_pjsip.so'], { timeout: 15000 }, (e, so) => (e ? reject(e) : resolve(so))));
async function writeAll() {
  const rows = await S.all('SELECT * FROM "BrowserCallExtension" ORDER BY "extension"');
  const tmp = `${ENV.pjsipFile}.tmp`;
  fs.writeFileSync(tmp, render(rows), { mode: 0o600 });
  fs.renameSync(tmp, ENV.pjsipFile);
  await reload();
}

async function extensionFor(userId) {
  let row = await S.one('SELECT * FROM "BrowserCallExtension" WHERE "userId"=?', userId);
  if (row) return row;
  const last = await S.one('SELECT MAX(CAST("extension" AS INTEGER)) AS m FROM "BrowserCallExtension"');
  const ext = String(Math.max(ENV.extStart, (last && last.m ? last.m + 1 : ENV.extStart)));
  const id = crypto.randomUUID();
  await S.run('INSERT INTO "BrowserCallExtension" ("id","userId","extension","secretEnc","active","createdAt") VALUES (?,?,?,?,1,?)', id, userId, ext, encryptSecret(newSecret()), S.nowIso());
  row = await S.one('SELECT * FROM "BrowserCallExtension" WHERE "id"=?', id);
  return row;
}

// start a softphone session: fresh password, written to Asterisk, returned once.
async function startSession(userId) {
  const row = await extensionFor(userId);
  const secret = newSecret();
  const expires = new Date(Date.now() + ENV.sessionMinutes * 60000).toISOString();
  await S.run('UPDATE "BrowserCallExtension" SET "secretEnc"=?, "rotatedAt"=?, "expiresAt"=? WHERE "id"=?', encryptSecret(secret), S.nowIso(), expires, row.id);
  await writeAll();
  return { extension: row.extension, password: secret, expiresAt: expires };
}
// switch an extension off (e.g. a login lost the right) - removed from Asterisk on the next write
async function disable(userId) { await S.run('UPDATE "BrowserCallExtension" SET "active"=0 WHERE "userId"=?', userId); await writeAll(); }
module.exports = { startSession, extensionFor, writeAll, render, disable };
