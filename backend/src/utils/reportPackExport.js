// ---------------------------------------------------------------------------
// THE FILE WRITERS of the team / person reports (utils/reportPack.js).
//
// A report is ONE table object (columns, rows, total, title, period, filters,
// area). The screen draws that object; the Excel and the PDF below are written
// from the very same object, so a file can never differ from what was on the
// screen: same rows, same filters, same total. Every file carries a title,
// the period, the filters used, the area the reader may see, who made it and
// when.
//
// Excel: SheetJS (already a dependency). PDF: pdfkit (already used by ATS
// Reports). Nothing new is added. Numbers stay numbers in Excel so the sheet
// can be summed.
// ---------------------------------------------------------------------------
const XLSX = require('xlsx');
const PDFDocument = require('pdfkit');

const istStamp = (d = new Date()) => `${new Date(d.getTime() + 330 * 60000).toISOString().slice(0, 16).replace('T', ' ')} IST`;

// "Calls" -> "Calls"; "Sent to client" -> "Sent-to-client"
const fileWord = (s) => String(s || 'Report').replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'Report';

// TeamLink-Team-Calls-2026-10-01_to_2026-10-31
function fileBase(table) {
  const view = table.viewWord || (table.view === 'individual' ? 'Individual' : 'Team');
  return `TeamLink-${fileWord(view)}-${fileWord(table.reportLabel || table.title)}-${table.period.from}_to_${table.period.to}`;
}

const cellOut = (v) => (v === undefined || v === null ? '' : v);

// The lines every sheet / page starts with.
function headLines(table, meta) {
  const lines = [
    `TeamLink - ${table.title}`,
    `Period: ${table.period.label} (${table.period.from} to ${table.period.to})${table.groupLabel ? ` - ${table.groupLabel}` : ''}`,
    `View: ${table.viewLabel}`,
    `Filters: ${table.filterText}`,
    `Your area: ${table.scope}`,
    `Generated by ${meta.by} on ${meta.at}`,
  ];
  return lines;
}

function sheetAoa(table, meta) {
  const aoa = headLines(table, meta).map((l) => [l]);
  aoa.push([]);
  const headerRow = aoa.length;
  aoa.push(table.columns.map((c) => c.label));
  table.rows.forEach((r) => aoa.push(r.c.map(cellOut)));
  if (table.total) aoa.push(table.total.map(cellOut));
  (table.notes || []).forEach((n, i) => { if (i === 0) aoa.push([]); aoa.push([`Note: ${n}`]); });
  return { aoa, headerRow };
}

function uniqueSheetName(used, wanted) {
  const base = String(wanted || 'Sheet').replace(/[\\/?*[\]:]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 31) || 'Sheet';
  let name = base;
  for (let n = 2; used.has(name.toLowerCase()); n += 1) name = `${base.slice(0, 27)} (${n})`;
  used.add(name.toLowerCase());
  return name;
}

function addTableSheet(wb, used, table, meta, sheetName) {
  const { aoa } = sheetAoa(table, meta);
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  const widths = table.columns.map((c, i) => Math.min(40, Math.max(10, String(c.label).length + 2,
    ...table.rows.slice(0, 300).map((r) => String(r.c[i] === null || r.c[i] === undefined ? '' : r.c[i]).length + 2))));
  ws['!cols'] = widths.map((wch) => ({ wch }));
  XLSX.utils.book_append_sheet(wb, ws, uniqueSheetName(used, sheetName || table.sheetName || table.reportLabel || table.title));
}

// One workbook: [{ name, table }] (+ an optional first "About" sheet of plain lines).
function toWorkbook(sheets, meta, about = null) {
  const wb = XLSX.utils.book_new();
  const used = new Set();
  if (about && about.length) {
    const ws = XLSX.utils.aoa_to_sheet(about.map((l) => (Array.isArray(l) ? l : [l])));
    ws['!cols'] = [{ wch: 44 }, { wch: 60 }, { wch: 14 }];
    XLSX.utils.book_append_sheet(wb, ws, uniqueSheetName(used, 'About this file'));
  }
  sheets.forEach((s) => {
    if (s.lines) { // a free sheet: { name, lines: [[...]] }
      const ws = XLSX.utils.aoa_to_sheet(s.lines);
      ws['!cols'] = (s.widths || []).map((wch) => ({ wch }));
      XLSX.utils.book_append_sheet(wb, ws, uniqueSheetName(used, s.name));
    } else addTableSheet(wb, used, s.table, meta, s.name);
  });
  return XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
}

function toCsv(table, meta) {
  const q = (v) => {
    const s = v === null || v === undefined ? '' : String(v);
    return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const lines = headLines(table, meta).map((l) => q(l));
  lines.push('');
  lines.push(table.columns.map((c) => q(c.label)).join(','));
  table.rows.forEach((r) => lines.push(r.c.map(q).join(',')));
  if (table.total) lines.push(table.total.map(q).join(','));
  return `﻿${lines.join('\r\n')}`;
}

// pdfkit's built-in Helvetica is Latin-1 only.
const pdfText = (v) => String(v === null || v === undefined ? '' : v)
  .replace(/[–—]/g, '-').replace(/→/g, '->').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/₹/g, 'Rs ').replace(/·/g, '-')
  .replace(/[^\x09\x0A\x0D\x20-\xFF]/g, '');
const ROW_CAP = 1500;
const fmtPdf = (v, type) => {
  if (v === null || v === undefined || v === '') return type === 'text' ? '' : '-';
  if (type === 'money') return `Rs ${Math.round(Number(v)).toLocaleString('en-IN')}`;
  if (type === 'pct') return `${v}%`;
  if (typeof v === 'number') return v.toLocaleString('en-IN');
  return v;
};

// Writes one table to a PDF stream (A4 landscape, header repeated on every page).
function toPdf(table, meta, out) {
  const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 28, info: { Title: `TeamLink ${table.title}`, Author: meta.by } });
  doc.pipe(out);
  const W = doc.page.width - 56;
  const bottom = () => doc.page.height - 34;
  doc.font('Helvetica-Bold').fontSize(15).fillColor('#1f2a44').text(pdfText(`TeamLink - ${table.title}`));
  doc.font('Helvetica').fontSize(8.5).fillColor('#5b6474');
  headLines(table, meta).slice(1).forEach((l) => doc.text(pdfText(l)));
  doc.moveDown(0.6);

  const cols = table.columns;
  const manyCols = cols.length > 16;
  const size = cols.length > 22 ? 5.6 : manyCols ? 6.4 : cols.length > 12 ? 7 : 8;
  const lineH = size + 5;
  const rows = table.rows.map((r) => r.c.map((v, i) => fmtPdf(v, cols[i].type)));
  const total = table.total ? table.total.map((v, i) => (i === 0 ? 'Total' : fmtPdf(v, cols[i].type))) : null;
  const heads = cols.map((c) => (manyCols && c.short ? c.short : c.label));
  const sample = [heads, ...rows.slice(0, 300), ...(total ? [total] : [])];
  // Text columns get the room, numeric ones what their longest value needs.
  const want = cols.map((c, i) => Math.min(c.type === 'text' ? 30 : 11, Math.max(c.type === 'text' ? 12 : 4, ...sample.map((r) => String(r[i] ?? '').length))));
  const sum = want.reduce((s, n) => s + n, 0);
  const widths = want.map((n) => (n / sum) * W);
  const fit = (s, w) => {
    const t = pdfText(s);
    const max = Math.max(1, Math.floor(w / (size * 0.5)));
    return t.length > max ? `${t.slice(0, Math.max(1, max - 1))}.` : t;
  };
  const drawRow = (cells, bold, shade) => {
    if (doc.y + lineH > bottom()) { doc.addPage(); drawRow(heads, true, true); }
    const y = doc.y;
    if (shade) doc.rect(28, y - 1, W, lineH).fill('#eef1f6');
    let x = 28;
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(size).fillColor('#111');
    cells.forEach((c, i) => {
      doc.text(fit(c, widths[i] - 4), x + 2, y + 1, { width: widths[i] - 4, align: cols[i].type === 'text' ? 'left' : 'right', lineBreak: false });
      x += widths[i];
    });
    doc.y = y + lineH;
  };
  drawRow(heads, true, true);
  rows.slice(0, ROW_CAP).forEach((r) => drawRow(r, false, false));
  if (rows.length > ROW_CAP) {
    doc.font('Helvetica-Oblique').fontSize(8).fillColor('#5b6474').text(`First ${ROW_CAP} of ${rows.length} rows - the Excel file carries all of them.`, 28, doc.y + 2);
  }
  if (total) drawRow(total, true, true);
  if (!rows.length) doc.font('Helvetica-Oblique').fontSize(9).fillColor('#5b6474').text('Nothing for these filters.', 28, doc.y + 4);
  (table.notes || []).forEach((n) => { doc.moveDown(0.4); doc.font('Helvetica-Oblique').fontSize(8).fillColor('#5b6474').text(pdfText(`Note: ${n}`), 28); });
  doc.end();
}

module.exports = {
  istStamp, fileBase, fileWord, sheetAoa, toWorkbook, toCsv, toPdf, headLines,
};
