// ---------------------------------------------------------------------------
// HR LETTERS FOR ONE EMPLOYEE (2026-11-26, owner: templates for the appointment, relieving, experience, appraisal and internship letters,
// filled with the employee's own name and details, sent to them when HR presses Send).
//
//   appointment             any employee on the payroll (not an intern, not a leaver)
//   experience / relieving  the exit letters TeamLink already makes (utils/exitLetters.js); only Send is added here
//   appraisal               from the salary versions in Payroll: the letter never promises a pay that Payroll does not hold
//   internshipOffer / internshipCertificate   interns; the dates, duration and notice are typed by HR
//
// NOTHING SENDS BY ITSELF. HR previews and presses Send, and Send works only after sending is switched on
// (AppSetting "hr-letters" { "sendEnabled": true }), which waits for the owner to say which address the letters go from.
// The wording follows the company's HR documents (26 Nov 2026); change the sentences in modelOf below.
// ---------------------------------------------------------------------------
const prisma = require('../db');
const { logAudit } = require('./audit');
const exitLetters = require('./exitLetters');

const SETTINGS_KEY = 'hr-letters';
const GENERATED = 'Generated by TeamLink'; // EmployeeDocument.docName of a file TeamLink made
const LEFT = ['Relieved', 'Exited', 'Terminated'];
// letters that show pay: the filed copy is shown only to the person and the HR desk (routes/employees.js)
const PAY_LETTER_TYPES = ['Appointment Letter', 'Appraisal Letter'];
const NOTICE_TEXT = '15 days during probation / 1 month after confirmation';
const HOURS = '09:00 AM - 06:00 PM';
const DAYS = 'Monday to Saturday';

const KINDS = {
  appointment: { title: 'Appointment Letter', docType: 'Appointment Letter', fields: [{ key: 'acceptBy', label: 'Sign and return by (optional)', type: 'date' }] },
  experience: { title: 'Experience Letter (Service Certificate)', docType: 'Service Certificate', exit: 'service', fields: [] },
  relieving: { title: 'Relieving Letter', docType: 'Relieving Letter', exit: 'relieving', fields: [] },
  appraisal: {
    title: 'Salary Appraisal Letter', docType: 'Appraisal Letter', fields: [
      { key: 'reviewPeriod', label: 'Review period, for example April 2025 to March 2026', type: 'text' },
      { key: 'previousCtc', label: 'Previous yearly CTC in rupees (only if Payroll has no earlier salary)', type: 'number' },
    ],
  },
  internshipOffer: {
    title: 'Internship Offer Letter', docType: 'Internship Offer Letter', fields: [
      { key: 'role', label: 'Internship role', type: 'text' },
      { key: 'startDate', label: 'Start date', type: 'date' },
      { key: 'months', label: 'Duration in months', type: 'number' },
      { key: 'stipend', label: 'Stipend per month in rupees (0 = unpaid)', type: 'number' },
      { key: 'reportingTo', label: 'Reporting to', type: 'text' },
      { key: 'mode', label: 'Mode: on-site, hybrid or remote', type: 'text' },
      { key: 'noticeDays', label: 'Notice in days if the company ends it', type: 'number' },
      { key: 'acceptBy', label: 'Sign and return by (optional)', type: 'date' },
    ],
  },
  internshipCertificate: {
    title: 'Internship Completion Certificate', docType: 'Internship Completion Certificate', fields: [
      { key: 'role', label: 'Internship role', type: 'text' },
      { key: 'startDate', label: 'Start date', type: 'date' },
      { key: 'endDate', label: 'End date', type: 'date' },
      { key: 'summary', label: 'What the intern worked on (optional)', type: 'text' },
    ],
  },
};

// --- small helpers -------------------------------------------------------------------------------------------------------
const clean = (v, n = 120) => String(v == null ? '' : v).replace(/[\u0000-\u001f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, n);
const istDay = (v) => {
  if (!v) return '';
  const d = v instanceof Date ? v : new Date(String(v).length === 10 ? `${v}T00:00:00Z` : v);
  return Number.isNaN(d.getTime()) ? '' : new Date(d.getTime() + 330 * 60000).toISOString().slice(0, 10);
};
const today = () => istDay(new Date());
const isDay = (v) => /^\d{4}-\d{2}-\d{2}$/.test(String(v || '')) && !Number.isNaN(Date.parse(`${v}T00:00:00Z`)) && new Date(`${v}T00:00:00Z`).toISOString().startsWith(v);
const longDay = (d) => (d ? new Date(`${d}T00:00:00Z`).toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }) : '');
// the last day of an internship of n months that starts on `start`
function endOfMonths(start, n) {
  const [y, m, d] = start.split('-').map(Number);
  const lastOfTarget = new Date(Date.UTC(y, m - 1 + n + 1, 0)).getUTCDate();
  const same = new Date(Date.UTC(y, m - 1 + n, Math.min(d, lastOfTarget)));
  if (d <= lastOfTarget) same.setUTCDate(same.getUTCDate() - 1);
  return same.toISOString().slice(0, 10);
}
const rupees = (n) => `Rs. ${Math.round(Number(n) || 0).toLocaleString('en-IN')}`;
const num = (v) => (v === '' || v == null || !Number.isFinite(Number(v)) ? null : Number(v));
const p = (t) => [{ b: false, t }];
// a sentence that ends in the company's name: "... Pvt. Ltd." already has its full stop
const ending = (t) => (t.endsWith('.') ? t : `${t}.`);

async function sendEnabled() {
  const row = await prisma.appSetting.findUnique({ where: { key: SETTINGS_KEY } }).catch(() => null);
  try { return !!row && JSON.parse(row.value).sendEnabled === true; } catch { return false; }
}

// --- the facts of one employee -------------------------------------------------------------------------------------------
async function factsFor(employeeId) {
  const employee = await prisma.employee.findUnique({ where: { id: employeeId }, include: { user: true, reportingManager: true, salaryStructure: true } });
  if (!employee) return null;
  const [companyRow, signatory, versions, exitRecord, probation] = await Promise.all([
    prisma.company.findFirst().catch(() => null),
    exitLetters.loadSettings(),
    prisma.salaryStructureVersion.findMany({ where: { employeeId }, orderBy: { effectiveFrom: 'desc' } }),
    prisma.employeeRecord.findFirst({ where: { employeeId, type: 'RESIGNATION', status: { notIn: ['Rejected', 'Withdrawn'] } }, orderBy: { createdAt: 'desc' }, include: { employee: true } }),
    require('./probationLength').getSettings(), // eslint-disable-line global-require
  ]);
  const company = require('./companyContact').forLetter(companyRow); // eslint-disable-line global-require
  const lead = !!(employee.user && [employee.user.role, employee.user.hrmsRole].includes('TL')); // Team Leads have the shorter probation (utils/probationLength.js)
  const manager = employee.reportingManager;
  return {
    employee,
    company,
    signatory,
    versions,
    salary: versions[0] || employee.salaryStructure || null,
    exitRecord,
    probationMonths: lead ? probation.leadMonths : probation.months,
    name: clean(employee.name),
    first: clean(employee.name).split(' ')[0] || 'there',
    code: clean(employee.employeeCode, 40),
    designation: clean(employee.designation),
    department: clean(employee.department),
    place: clean(employee.branch || employee.location || employee.city),
    manager: manager ? clean(`${manager.name}${manager.designation ? `, ${manager.designation}` : ''}`) : '',
    joined: istDay(employee.dateOfJoining),
    left: LEFT.includes(employee.employmentStatus),
    intern: employee.employeeType === 'Intern',
    address: [employee.addressLine1 || employee.address, employee.addressLine2, [employee.city, employee.state, employee.postalCode].filter(Boolean).join(', ')].map((x) => clean(x, 160)).filter(Boolean),
  };
}

// what the screen fills into the boxes before HR types anything
function defaultsOf(kind, f) {
  const stipend = f.salary && Number(f.salary.stipend) > 0 ? Math.round(f.salary.stipend) : '';
  if (kind === 'internshipOffer') return { role: f.designation, startDate: f.joined, stipend, reportingTo: f.manager, mode: 'on-site' };
  if (kind === 'internshipCertificate') return { role: f.designation, startDate: f.joined };
  return {};
}
const inputOf = (kind, f, typed) => {
  const out = { ...defaultsOf(kind, f) };
  for (const field of KINDS[kind].fields) {
    const v = typed ? typed[field.key] : undefined;
    if (v !== undefined && String(v).trim() !== '') out[field.key] = clean(v, field.key === 'summary' ? 600 : 160);
  }
  return out;
};

// Why this letter cannot be made for this person at all (from the record); null = it can.
function recordBlocker(kind, f) {
  if (kind === 'appointment') {
    if (f.left) return 'This person has left, so there is no appointment letter.';
    if (f.intern) return 'This person is an intern: use the Internship Offer Letter.';
    if (!f.designation) return 'The designation is not on the record.';
    if (!f.joined) return 'The date of joining is not on the record.';
    if (!f.salary || !(Number(f.salary.ctc) > 0 || Number(f.salary.stipend) > 0)) return 'The salary is not set in Payroll > Salary Structure.';
  }
  if (kind === 'appraisal') {
    if (f.left) return 'This person has left, so there is no appraisal letter.';
    if (!f.versions[0] || !(Number(f.versions[0].ctc) > 0)) return 'There is no salary in Payroll > Salary Structure. Save the revised salary there first.';
  }
  if (kind === 'internshipOffer') {
    if (f.left) return 'This person has left.';
    if (!f.intern) return 'Only for interns: set the employee type to Intern first.';
  }
  return null;
}

// What HR still has to type; null = complete.
function inputBlocker(kind, f, i) {
  if (kind === 'appointment' && i.acceptBy && !isDay(i.acceptBy)) return 'The "sign and return by" date is not a date.';
  if (kind === 'appraisal') {
    if (!i.reviewPeriod) return 'Type the review period.';
    if (!f.versions[1] && !(num(i.previousCtc) > 0)) return 'Payroll has no earlier salary: type the previous yearly CTC.';
  }
  if (kind === 'internshipOffer') {
    if (!i.role) return 'Type the internship role.';
    if (!isDay(i.startDate)) return 'Type the start date.';
    if (!(Number.isInteger(num(i.months)) && num(i.months) >= 1 && num(i.months) <= 24)) return 'Type the duration in months (1 to 24).';
    if (num(i.stipend) === null || num(i.stipend) < 0) return 'Type the monthly stipend (0 if unpaid).';
    if (!(Number.isInteger(num(i.noticeDays)) && num(i.noticeDays) >= 0 && num(i.noticeDays) <= 90)) return 'Type the notice in days (0 to 90).';
    if (i.acceptBy && !isDay(i.acceptBy)) return 'The "sign and return by" date is not a date.';
  }
  if (kind === 'internshipCertificate') {
    if (!i.role) return 'Type the internship role.';
    if (!isDay(i.startDate)) return 'Type the start date.';
    if (!isDay(i.endDate)) return 'Type the end date.';
    if (i.endDate < i.startDate) return 'The end date is before the start date.';
    if (i.endDate > today()) return `The certificate can be made after the internship ends (${longDay(i.endDate)}).`;
  }
  return null;
}

// the pay table of one salary version (components are monthly in Payroll, CTC is yearly)
function payTable(s) {
  const parts = [['Basic salary', s.basic], ['House rent allowance', s.hra], ['Special allowance', s.specialAllowance], ['Conveyance allowance', s.conveyance], ['Bonus', s.bonus]].filter(([, v]) => Number(v) > 0);
  const gross = parts.reduce((a, [, v]) => a + Number(v), 0);
  const extra = [['Employer PF contribution', s.employerPf], ['Employer ESI contribution', s.esiEmployer], ['Gratuity provision', s.gratuity]].filter(([, v]) => Number(v) > 0);
  const line = ([k, v]) => [k, rupees(v), rupees(v * 12)];
  return [['Component', 'Monthly', 'Yearly'], ...parts.map(line), ...(gross > 0 ? [line(['Monthly gross', gross])] : []), ...extra.map(line), ['Cost to company (CTC)', rupees(s.ctc / 12), rupees(s.ctc)]];
}
const grossOf = (s) => ['basic', 'hra', 'specialAllowance', 'conveyance', 'bonus'].reduce((a, k) => a + (Number(s[k]) || 0), 0);

// The letter as data, drawn by utils/exitLetters.js renderPdf.
function modelOf(kind, f, i) {
  const co = f.company.name;
  const meta = KINDS[kind];
  const sign = { company: co, name: f.signatory.signatoryName, title: f.signatory.signatoryTitle, png: f.signatory.png || null };
  const base = {
    kind, title: meta.title.toUpperCase(), company: f.company, date: longDay(today()), dateAlign: 'left',
    to: [f.name, f.code ? `Employee Code: ${f.code}` : null, ...f.address].filter(Boolean),
    heading: null, subject: null, salutation: `Dear ${f.first},`, sign,
    fileName: `${meta.docType} - ${f.name}${f.code ? ` (${f.code})` : ''}.pdf`,
  };

  if (kind === 'appointment') {
    const s = f.salary;
    const paid = Number(s.ctc) > 0;
    const probation = `${f.probationMonths} months from the date of joining`;
    return {
      ...base,
      subject: `Subject: Appointment as ${f.designation}`,
      paras: [
        p(`${ending(`Welcome to ${co}`)} We are pleased to appoint you as ${f.designation}${f.department ? ` in the ${f.department} department` : ''}${f.place ? ` at our ${f.place} office` : ''}, on the terms below.`),
        { table: [
          ['Date of joining', longDay(f.joined)],
          ['Designation', f.designation],
          ['Department', f.department || '-'],
          ['Reporting manager', f.manager || '-'],
          ['Place of work', f.place || '-'],
          ['Employment type', clean(f.employee.employeeType) || 'Full-time'],
          ['Probation', probation],
          paid ? ['Compensation', `Yearly CTC of ${rupees(s.ctc)}, as in the annexure. Pay is subject to statutory deductions.`] : ['Stipend', `${rupees(s.stipend)} per month, subject to statutory deductions where applicable.`],
          ['Pay date', "As per the company's Salary and Payroll Policy, by bank transfer"],
          ['Working hours', `${HOURS}, ${DAYS}`],
          ['Notice period', NOTICE_TEXT],
        ] },
        p('Your employment is governed by the policies of the company, which you will receive on joining and must acknowledge. These include the Employee Handbook, the Leave Policy, the Attendance Policy, the Disciplinary Policy and the policy on prevention of sexual harassment.'),
        p('Your appointment is subject to: (a) submission of your original documents, including identity proof, address proof, educational certificates, previous relieving and experience letters and recent pay slips, if applicable, within the time given by HR; (b) satisfactory background verification; and (c) satisfactory completion of probation.'),
        p('You are expected to devote your full working time to the company. During employment you must not take up any other paid work without written approval. Confidentiality obligations continue after your employment ends.'),
        p('Either party may end employment by giving the notice stated above. The company may pay salary in lieu of notice. After you complete six months of service, the company will end your employment only for reasonable cause, with at least one month’s notice in writing or salary in lieu, except where the law allows otherwise.'),
        p(i.acceptBy ? `Please sign and return a copy of this letter by ${longDay(i.acceptBy)} to confirm your acceptance.` : 'Please sign and return a copy of this letter to confirm your acceptance.'),
        p('We look forward to a productive association.'),
      ],
      accept: f.name,
      annexure: paid ? { title: 'Annexure - Compensation details', table: payTable(s) } : null,
    };
  }

  if (kind === 'appraisal') {
    const now = f.versions[0];
    const before = f.versions[1] || null;
    const prevCtc = before ? Number(before.ctc) : num(i.previousCtc);
    const effective = longDay(now.effectiveFrom);
    const rows = [['Item', 'Current', 'Revised'], ['Yearly CTC', rupees(prevCtc), rupees(now.ctc)], ['Monthly CTC', rupees(prevCtc / 12), rupees(now.ctc / 12)]];
    if (before && grossOf(before) > 0 && grossOf(now) > 0) rows.push(['Monthly gross', rupees(grossOf(before)), rupees(grossOf(now))]);
    return {
      ...base,
      subject: `Subject: Salary appraisal, effective ${effective}`,
      paras: [
        p(`Based on your performance during ${i.reviewPeriod} and the outcome of your review, we are pleased to inform you that your salary${f.designation ? ` as ${f.designation}` : ''} is revised as follows, with effect from ${effective}.`),
        { table: rows, head: true },
        p('The revised structure is shown in the annexure. Statutory deductions shown on your payslip will reflect the revised pay from the effective date.'),
        p('Thank you for your contribution. We look forward to your continued growth with the company.'),
      ],
      accept: f.name,
      annexure: { title: 'Annexure - Revised salary structure', table: payTable(now) },
    };
  }

  if (kind === 'internshipOffer') {
    const months = num(i.months);
    const stipend = num(i.stipend);
    const end = endOfMonths(i.startDate, months);
    return {
      ...base,
      compact: true,
      subject: `Subject: Internship offer - ${i.role}`,
      paras: [
        p(`${ending(`Thank you for applying to ${co}`)} We are pleased to offer you an internship as ${i.role}${f.department ? ` in the ${f.department} department` : ''}${f.place ? `, based at ${f.place}` : ''}, on the following terms.`),
        { table: [
          ['Start date', longDay(i.startDate)],
          ['Duration', `${months} month${months === 1 ? '' : 's'}, ending on ${longDay(end)}. It may be extended by mutual written agreement.`],
          ['Mode', i.mode || 'on-site'],
          ['Working hours', `${HOURS}, ${DAYS}`],
          ['Stipend', stipend > 0 ? `${rupees(stipend)} per month` : 'Unpaid'],
          ['Reporting to', i.reportingTo || '-'],
          ['Certificate', 'Internship Completion Certificate on successful completion'],
        ] },
        p(`The internship is a learning opportunity. It does not create an employment relationship, and it does not guarantee a job offer after completion. The company may end the internship with ${num(i.noticeDays)} days’ notice for misconduct or non-performance.`),
        p('You must keep company and client information confidential, follow the company policies on conduct, data protection, IT use and prevention of sexual harassment, and return all company property at the end of the internship.'),
        p(i.acceptBy ? `Please sign and return a copy by ${longDay(i.acceptBy)} to accept this offer.` : 'Please sign and return a copy to accept this offer.'),
      ],
      accept: f.name,
    };
  }

  // internshipCertificate
  return {
    ...base,
    title: 'CERTIFICATE OF INTERNSHIP COMPLETION',
    to: null, salutation: null, heading: 'TO WHOM IT MAY CONCERN',
    paras: [
      [{ b: false, t: 'This is to certify that ' }, { b: true, t: f.name }, { b: false, t: ` has successfully completed an internship with ${co} as ${i.role}${f.department ? ` in the ${f.department} department` : ''} from ${longDay(i.startDate)} to ${longDay(i.endDate)}.` }],
      ...(i.summary ? [p(i.summary)] : []),
      p('We wish them every success in their future endeavours.'),
    ],
  };
}

// -> { pdf, fileName, facts } | { error, status }
async function pdfFor(employeeId, kind, typed, facts) {
  const meta = KINDS[kind];
  if (!meta) return { error: 'Unknown letter.', status: 404 };
  const f = facts || await factsFor(employeeId);
  if (!f) return { error: 'Employee not found.', status: 404 };
  if (meta.exit) {
    if (!f.exitRecord) return { error: 'There is no resignation or exit record yet (HRMS > Resignation).', status: 409 };
    const out = await exitLetters.pdfFor(f.exitRecord, meta.exit);
    return out.error ? out : { pdf: out.pdf, fileName: out.fileName, facts: f };
  }
  const input = inputOf(kind, f, typed);
  const why = recordBlocker(kind, f) || inputBlocker(kind, f, input);
  if (why) return { error: why, status: 409 };
  const model = modelOf(kind, f, input);
  return { pdf: await exitLetters.renderPdf(model), fileName: model.fileName, facts: f, model };
}

const emailsOf = (kind, e) => {
  // a leaver or a new joiner may not read (or have) the work mailbox: the personal address comes first for them
  const personalFirst = ['appointment', 'experience', 'relieving', 'internshipOffer', 'internshipCertificate'].includes(kind);
  const list = personalFirst ? [e.personalEmail, e.email] : [e.email, e.personalEmail];
  return String(list.find((x) => String(x || '').trim()) || '').trim();
};

// What the screen lists: each letter, whether it can be made (and why not), the boxes to fill, where it would go.
async function listFor(employeeId) {
  const f = await factsFor(employeeId);
  if (!f) return null;
  const docs = await prisma.employeeDocument.findMany({ where: { employeeId, docName: GENERATED, docType: { in: Object.values(KINDS).map((k) => k.docType) } }, orderBy: { uploadedAt: 'desc' }, select: { docType: true, uploadedAt: true } });
  const letters = [];
  for (const [key, meta] of Object.entries(KINDS)) {
    let why = null;
    if (!meta.exit) why = recordBlocker(key, f);
    else if (!f.exitRecord) why = 'There is no resignation or exit record yet (HRMS > Resignation).';
    else why = exitLetters.blockerOf(meta.exit, await exitLetters.factsFor(f.exitRecord)); // eslint-disable-line no-await-in-loop
    const filed = docs.find((d) => d.docType === meta.docType);
    letters.push({ key, title: meta.title, why, fields: meta.fields, defaults: defaultsOf(key, f), emailTo: emailsOf(key, f.employee), filedAt: filed ? filed.uploadedAt : null });
  }
  return { letters, sendOn: await sendEnabled() };
}

const oneAddress = (v) => /^[^@\s,;<>]+@[^@\s,;<>]+\.[^@\s,;<>]+$/.test(v);

// HR pressed Send: the letter is made fresh, kept in the employee's documents and emailed as a PDF.
// -> { state: 'SENT', to } | { state: 'NOT_SENT', message }
async function send(employeeId, kind, typed, actor, { to: typedTo } = {}) {
  const no = (message) => ({ state: 'NOT_SENT', message });
  const meta = KINDS[kind];
  if (!meta) return no('Unknown letter.');
  if (!await sendEnabled()) return no('Sending is switched off. It will be switched on once the sending address is decided. Use Preview until then.');
  const made = await pdfFor(employeeId, kind, typed);
  if (made.error) return no(made.error);
  const f = made.facts;
  const wanted = clean(typedTo, 200);
  if (wanted && !oneAddress(wanted)) return no(`"${wanted.slice(0, 80)}" is not a single, valid email address.`);
  const to = wanted || emailsOf(kind, f.employee);
  if (!oneAddress(to)) return no('There is no email address on this employee’s record. Type one, or add it to the record.');
  if (/\b(zz)?test\b|^zz/i.test(f.name)) return no('A test person is never mailed.');

  if (meta.exit) {
    const filed = await exitLetters.issue(f.exitRecord, meta.exit, actor); // files it, audits it, ticks the exit checklist
    if (filed.error) return no(filed.error);
  } else {
    const { fileDocument } = require('./internalOnboarding'); // eslint-disable-line global-require
    await fileDocument(f.employee.id, meta.docType, made.pdf, made.fileName, actor ? actor.id : null);
    await logAudit({ userId: actor ? actor.id : null, action: `${meta.title} generated`, entity: 'Employee', entityId: f.employee.id, toValue: `${f.name} (${f.code})` });
  }

  const text = [`Dear ${f.first},`, '', ending(`Please find attached your ${meta.title} from ${f.company.name}`), '', 'If you have any question, just reply to this email.', '', 'Regards,', `HR, ${f.company.name}`].join('\n');
  const out = await require('./mailer').sendMail({ // eslint-disable-line global-require
    to, subject: `Your ${meta.title} - ${f.company.name}`, text,
    attachments: [{ filename: made.fileName, content: made.pdf, contentType: 'application/pdf' }],
    senderEmail: actor && actor.email ? actor.email : undefined, useEmployeeFrom: false, fromName: 'TeamLink HR',
  });
  // the audit log carries who and which address, never the salary
  if (!out || !out.ok) {
    const why = (out && out.error) || 'mail is not set up';
    await logAudit({ userId: actor ? actor.id : null, action: `${meta.title} email NOT sent`, entity: 'Employee', entityId: f.employee.id, toValue: `${f.name} (${f.code}) <${to}>: ${String(why).slice(0, 300)}` });
    return no(`The letter is kept in the documents, but the email was not sent: ${why}`);
  }
  await logAudit({ userId: actor ? actor.id : null, action: `${meta.title} emailed to the employee`, entity: 'Employee', entityId: f.employee.id, toValue: `${f.name} (${f.code}) <${to}>${wanted ? ' (address typed by HR)' : ''}` });
  return { state: 'SENT', to };
}

// A filed copy of a pay letter is only for the person and the HR desk. access = { self, desk }
const payLetterHidden = (access, doc) => !!doc && doc.docName === GENERATED && PAY_LETTER_TYPES.includes(doc.docType) && !access.self && !access.desk;

module.exports = { KINDS, SETTINGS_KEY, PAY_LETTER_TYPES, factsFor, recordBlocker, inputBlocker, modelOf, endOfMonths, pdfFor, listFor, send, sendEnabled, payLetterHidden };
