// ---------------------------------------------------------------------------
// THE EXIT LETTERS: SERVICE CERTIFICATE (experience letter) AND RELIEVING LETTER (2026-11-23, from the founder's reference letters
// "Experience Letter_7.docx" and "Relieving_Letter_Teamlink-v3.docx").
//
// WHO: an employee who resigned (an EmployeeRecord of type RESIGNATION). Both letters are filled in from the records, so HR types
// nothing: the name, employee code, designation and joining date from the employee; the resignation date and the last working day
// from the resignation (utils/exitDate.js); full & final from Payroll (FnfRequest).
//
// WHEN: from the employee's last working day (or once they are marked Relieved). Before that the letters say why they are not ready.
//   Service certificate  needs the date of joining and the last working day.
//   Relieving letter     needs the resignation date and the last working day. The line "your full and final settlement ... has
//                        been processed" is printed ONLY when Payroll shows the F&F as Processed; otherwise it is left out, never
//                        claimed.
//
// WHAT HR DOES (Resignation details / Exit record -> Exit letters): Preview the PDF, or "Generate and save", which files the PDF in
// the employee's documents (Service Certificate / Relieving Letter; a newer one replaces the older one TeamLink made), writes the
// audit log, and for the service certificate ticks "Experience letter given" on the offboarding checklist.
// The signatory's name and title are one setting (AppSetting "exit-letters"), typed once by HR.
// ---------------------------------------------------------------------------
const prisma = require('../db');
const { logAudit } = require('./audit');
const exitDate = require('./exitDate');

const SETTINGS_KEY = 'exit-letters';
const LSTYLE = require('./letterStyle'); // the brand look shared with the offer letter (founder's formatting brief, 2026-11-25)
const { NAVY } = LSTYLE;
const LEFT = ['Relieved', 'Exited', 'Terminated'];

const KINDS = {
  service: { key: 'service', title: 'Service Certificate', docType: 'Service Certificate', file: 'Service Certificate' },
  relieving: { key: 'relieving', title: 'Relieving Letter', docType: 'Relieving Letter', file: 'Relieving Letter' },
};
const GENERATED = 'Generated by TeamLink'; // EmployeeDocument.docName of a file TeamLink made (utils/internalOnboarding.js)

// --- dates ---------------------------------------------------------------------------------------------------------------
const isDay = (v) => /^\d{4}-\d{2}-\d{2}/.test(String(v || ''));
const dayOf = (v) => {
  if (!v) return null;
  if (v instanceof Date) return Number.isNaN(v.getTime()) ? null : new Date(v.getTime() + 330 * 60000).toISOString().slice(0, 10);
  return isDay(v) ? String(v).slice(0, 10) : null;
};
const istToday = () => new Date(Date.now() + 330 * 60000).toISOString().slice(0, 10);
const asUtc = (d) => new Date(`${d}T00:00:00Z`);
const longDay = (d) => (d ? asUtc(d).toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }) : '');
const dmy = (d) => (d ? `${d.slice(8, 10)}-${d.slice(5, 7)}-${d.slice(0, 4)}` : '');

// --- settings: who signs -------------------------------------------------------------------------------------------------
const clean = (v, n) => String(v == null ? '' : v).replace(/[\u0000-\u001f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, n);
async function loadSettings() {
  // the company's letter signatory, set once in Company Setup (utils/letterSignatory.js): the same person signs every letter
  const sig = await require('./letterSignatory').load(); // eslint-disable-line global-require
  return {
    signatoryName: sig.name,
    signatoryTitle: sig.title || 'HR Department',
    png: sig.png,
    updatedByName: sig.updatedByName,
    updatedAt: sig.updatedAt,
  };
}
async function saveSettings(body, user) {
  // the same record as Company Setup's Letter signatory: a name and title typed here are the company's
  await require('./letterSignatory').save({ name: body && body.signatoryName, title: body && body.signatoryTitle }, user); // eslint-disable-line global-require
  return loadSettings();
}

async function companyOf() {
  // the legal name as on the founder's letters, and no demo phone / email (utils/companyContact.js)
  const c = await prisma.company.findFirst().catch(() => null);
  return require('./companyContact').forLetter(c); // eslint-disable-line global-require
}

// --- the facts of one exit -----------------------------------------------------------------------------------------------
async function factsFor(record) {
  const employee = record.employee || await prisma.employee.findUnique({ where: { id: record.employeeId } });
  const [detail, fnf, company, settings] = await Promise.all([
    prisma.resignationDetail.findUnique({ where: { recordId: record.id } }),
    prisma.fnfRequest.findFirst({ where: { employeeId: employee.id }, orderBy: { createdAt: 'desc' } }).catch(() => null),
    companyOf(),
    loadSettings(),
  ]);
  const lastDay = dayOf(exitDate.dateOf(record, detail));
  const today = istToday();
  return {
    employee,
    company,
    settings,
    name: employee.name || (detail && detail.employeeName) || '',
    employeeCode: employee.employeeCode || (detail && detail.employeeCode) || '',
    designation: (detail && detail.designation) || employee.designation || '',
    place: [employee.branch || employee.location || employee.city, employee.state].filter(Boolean).join(', '),
    joined: dayOf(employee.dateOfJoining),
    resigned: dayOf(detail && detail.resignationDate),
    lastDay,
    today,
    relieved: record.status === 'Relieved' || LEFT.includes(employee.employmentStatus),
    lastDayReached: !!lastDay && lastDay <= today,
    stopped: ['Rejected', 'Withdrawn'].includes(record.status),
    fnfDone: !!fnf && fnf.status === 'Processed',
  };
}

// Why a letter cannot be made yet, in plain words; null = it can.
function blockerOf(kind, f) {
  if (f.stopped) return 'This resignation was withdrawn or rejected, so there is no exit letter.';
  if (!f.lastDay) return 'The last working day is not set yet.';
  if (!f.relieved && !f.lastDayReached) return `Ready on the last working day (${dmy(f.lastDay)}).`;
  if (kind === 'service' && !f.joined) return 'The date of joining is not on the employee’s record. Add it in Employees, then come back.';
  if (kind === 'relieving' && !f.resigned) return 'The resignation date is not set. Use “Edit dates” to add it.';
  return null;
}

// The letter as data (paragraphs), drawn by the PDF.
function modelOf(kind, f) {
  const co = f.company.name;
  const sign = { company: co, name: f.settings.signatoryName, title: f.settings.signatoryTitle, png: f.settings.png || null };
  if (kind === 'service') {
    return {
      kind, title: 'SERVICE CERTIFICATE', company: f.company, date: longDay(f.today), dateAlign: 'left', to: null,
      salutation: null, heading: 'TO WHOM IT MAY CONCERN', subject: null,
      paras: [
        [{ b: false, t: 'This is to certify that ' }, { b: true, t: f.name }, { b: false, t: `${f.employeeCode ? ` (Employee Code: ${f.employeeCode})` : ''} was employed with ${co}${f.designation ? ` as ${f.designation}` : ''} from ${longDay(f.joined)} to ${longDay(f.lastDay)}.` }],
        [{ b: false, t: `During their tenure with us, ${f.name} contributed significantly to the growth and success of the organization. Their dedication, professionalism, and commitment to excellence have been greatly appreciated.` }],
        [{ b: false, t: 'We acknowledge their valuable service and confirm that the employee is leaving the organization on their own accord. We wish them continued success in all their future endeavors.' }],
      ],
      sign,
      fileName: `${KINDS.service.file} - ${f.name}${f.employeeCode ? ` (${f.employeeCode})` : ''}.pdf`,
    };
  }
  const paras = [
    [{ b: false, t: `This has reference to your letter of resignation dated ${dmy(f.resigned)}, wherein you requested to be relieved from the services of the company. We wish to inform you that your resignation has been accepted, and you are hereby relieved from your duties at ${co} with effect from the close of office hours on ${dmy(f.lastDay)}.` }],
  ];
  if (f.fnfDone) paras.push([{ b: false, t: 'We further confirm that your full and final settlement of accounts has been successfully processed and cleared with the organization.' }]);
  paras.push([{ b: false, t: 'We thank you for your contributions during your tenure and wish you all the best in your future professional endeavors.' }]);
  return {
    kind, title: 'RELIEVING LETTER', company: f.company, date: dmy(f.today), dateAlign: 'right',
    to: [f.name, f.employeeCode ? `Employee Code: ${f.employeeCode}` : null, f.place || null].filter(Boolean),
    heading: null, subject: 'Subject: Relieving Letter', salutation: `Dear ${f.name},`,
    paras, sign,
    fileName: `${KINDS.relieving.file} - ${f.name}${f.employeeCode ? ` (${f.employeeCode})` : ''}.pdf`,
  };
}

// --- the PDF (pdfkit, A4, the same letterhead as the offer letter) -------------------------------------------------------
let logoCache = null;
async function logoPng() {
  if (logoCache !== null) return logoCache || null;
  try {
    const fs = require('fs'); // eslint-disable-line global-require
    const { LOGO } = require('./agreementPdf'); // eslint-disable-line global-require
    if (!fs.existsSync(LOGO)) { logoCache = false; return null; }
    logoCache = await require('sharp')(LOGO).resize({ width: 560, withoutEnlargement: true }).png({ compressionLevel: 9 }).toBuffer(); // eslint-disable-line global-require
  } catch { logoCache = false; }
  return logoCache || null;
}

async function renderPdf(m) {
  const PDFDocument = require('pdfkit'); // eslint-disable-line global-require
  const { pdfText } = require('./agreementPdf'); // eslint-disable-line global-require
  const t = (v) => pdfText(v);
  const logo = await logoPng();
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margins: { top: 44, bottom: 62, left: 64, right: 64 }, bufferPages: true, info: { Title: t(m.fileName.replace(/\.pdf$/, '')), Author: t(m.company.name) } });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c)); doc.on('end', () => resolve(Buffer.concat(chunks))); doc.on('error', reject);
    const L = doc.page.margins.left;
    const W = doc.page.width - L - doc.page.margins.right;

    // header: the TeamLink logo, the company name and tagline, a cyan line (utils/letterStyle.js)
    LSTYLE.drawHeader(doc, { L, W, logo, company: m.company, t });

    // title
    doc.font('Helvetica-Bold').fontSize(16).fillColor(NAVY).text(t(m.title), L, doc.y, { width: W, align: 'center', characterSpacing: 0.8 });
    const uy = doc.y + 3;
    doc.moveTo(L + W / 2 - 32, uy).lineTo(L + W / 2 + 32, uy).lineWidth(1.6).strokeColor(NAVY).stroke();
    doc.y = uy + 20; doc.x = L;

    // date
    doc.font('Helvetica-Bold').fontSize(10.5).fillColor('#111').text(t(`Date: ${m.date}`), L, doc.y, { width: W, align: m.dateAlign });
    doc.moveDown(1.2);

    if (m.to) {
      doc.font('Helvetica').fontSize(10.5).fillColor('#111').text('To,', L, doc.y, { width: W });
      m.to.forEach((line, i) => doc.font(i === 0 ? 'Helvetica-Bold' : 'Helvetica').fontSize(10.5).fillColor('#111').text(t(line), L, doc.y, { width: W }));
      doc.moveDown(1.1);
    }
    if (m.subject) { doc.font('Helvetica-Bold').fontSize(10.5).fillColor('#111').text(t(m.subject), L, doc.y, { width: W }); doc.moveDown(1); }
    if (m.heading) { doc.font('Helvetica-Bold').fontSize(11).fillColor('#111').text(t(m.heading), L, doc.y, { width: W, characterSpacing: 0.4 }); doc.moveDown(1); }
    if (m.salutation) { doc.font('Helvetica').fontSize(10.5).fillColor('#111').text(t(m.salutation), L, doc.y, { width: W }); doc.moveDown(0.8); }

    // the paragraphs (a run may be bold, e.g. the person's name)
    // pdfkit drops a space at the start of a continued run and stretches justified lines that mix fonts, so a mixed
    // paragraph keeps its spaces at the END of a run and is set ragged-right; a plain paragraph is justified.
    // a table ({ table: [[cell, ...]], head }) drawn with thin borders; the first column is bold, as is a heading row
    const drawTable = (rows, head) => {
      const cols = rows[0].length;
      const widths = cols === 2 ? [W * 0.3, W * 0.7] : [W * 0.4, ...Array(cols - 1).fill((W * 0.6) / (cols - 1))];
      rows.forEach((row, ri) => {
        const bold = (ci) => ci === 0 || (head && ri === 0);
        const height = Math.max(...row.map((cell, ci) => doc.font(bold(ci) ? 'Helvetica-Bold' : 'Helvetica').fontSize(9.5).heightOfString(t(cell), { width: widths[ci] - 12 }))) + 8;
        if (doc.y + height > doc.page.height - doc.page.margins.bottom) doc.addPage();
        const top = doc.y;
        let x = L;
        row.forEach((cell, ci) => {
          doc.rect(x, top, widths[ci], height).lineWidth(0.5).strokeColor('#b8bfcc').stroke();
          doc.font(bold(ci) ? 'Helvetica-Bold' : 'Helvetica').fontSize(9.5).fillColor('#222').text(t(cell), x + 6, top + 4.5, { width: widths[ci] - 12 });
          x += widths[ci];
        });
        doc.y = top + height; doc.x = L;
      });
    };
    const gap = m.compact ? 0.45 : 0.9; // m.compact: a longer letter that should still fit one page
    m.paras.forEach((raw) => {
      if (!Array.isArray(raw)) { drawTable(raw.table, raw.head); doc.moveDown(Math.max(gap, 0.65)); return; }
      const runs = raw.map((r) => ({ ...r }));
      for (let i = 1; i < runs.length; i += 1) {
        const lead = runs[i].t.match(/^\s+/);
        if (lead) { runs[i - 1].t += lead[0]; runs[i].t = runs[i].t.slice(lead[0].length); }
      }
      const align = runs.length > 1 ? 'left' : 'justify';
      runs.forEach((r, i) => {
        doc.font(r.b ? 'Helvetica-Bold' : 'Helvetica').fontSize(10.5).fillColor('#222');
        const opts = { width: W, lineGap: 3, align, continued: i < runs.length - 1 };
        if (i === 0) doc.text(t(r.t), L, doc.y, opts); else doc.text(t(r.t), opts);
      });
      doc.moveDown(gap);
    });

    // signature (kept on one page)
    const signRoom = (m.accept ? 200 : 130) - (m.compact ? 45 : 0);
    if (doc.y > doc.page.height - doc.page.margins.bottom - signRoom) doc.addPage();
    doc.moveDown(m.compact ? 0.2 : 0.6);
    doc.font('Helvetica').fontSize(10.5).fillColor('#222').text('Yours sincerely,', L, doc.y, { width: W });
    doc.font('Helvetica-Bold').text(t(`For ${m.sign.company}`), { width: W });
    doc.moveDown(m.compact ? 2.6 : 3);
    const sy = doc.y;
    if (m.sign.png) { try { doc.image(m.sign.png, L, sy - 36, { height: 32 }); } catch { /* the line stands alone */ } }
    doc.moveTo(L, sy).lineTo(L + 200, sy).lineWidth(0.8).strokeColor('#8b93a3').stroke();
    doc.y = sy + 5;
    doc.font('Helvetica-Bold').fontSize(10.5).fillColor('#111').text(t(m.sign.name || LSTYLE.SIGNATORY_FALLBACK), L, doc.y, { width: W });
    doc.font('Helvetica').fontSize(10).fillColor('#333').text(t(m.sign.title), L, doc.y, { width: W });

    if (m.accept) {
      doc.moveDown(m.compact ? 0.8 : 1.6);
      doc.font('Helvetica-Bold').fontSize(10.5).fillColor('#111').text('Accepted and agreed', L, doc.y, { width: W });
      doc.font('Helvetica').fontSize(10.5).fillColor('#222').text(t(`Name: ${m.accept}`), { width: W });
      doc.moveDown(m.compact ? 1 : 1.4);
      doc.text('Signature: ______________________          Date: ______________', { width: W });
    }
    if (m.annexure) {
      // on the same page when the whole table fits below the signature, otherwise on its own page
      if (doc.y + 80 + m.annexure.table.length * 24 > doc.page.height - doc.page.margins.bottom) doc.addPage(); else doc.moveDown(2);
      doc.font('Helvetica-Bold').fontSize(12).fillColor(NAVY).text(t(m.annexure.title), L, doc.y, { width: W });
      doc.moveDown(0.8);
      drawTable(m.annexure.table, true);
    }

    // footer on every page: address, phone, email and website
    LSTYLE.drawFooters(doc, { L, W, company: m.company, t });
    doc.end();
  });
}

// --- what the screen and the routes use ----------------------------------------------------------------------------------
async function issuedOf(employeeId) {
  const docs = await prisma.employeeDocument.findMany({
    where: { employeeId, docName: GENERATED, docType: { in: Object.values(KINDS).map((k) => k.docType) } },
    orderBy: { uploadedAt: 'desc' },
    select: { id: true, docType: true, fileName: true, uploadedAt: true, uploadedBy: true },
  });
  const ids = [...new Set(docs.map((d) => d.uploadedBy).filter(Boolean))];
  const users = ids.length ? await prisma.user.findMany({ where: { id: { in: ids } }, select: { id: true, name: true } }) : [];
  const nameOf = new Map(users.map((u) => [u.id, u.name]));
  return Object.fromEntries(Object.values(KINDS).map((k) => {
    const d = docs.find((x) => x.docType === k.docType);
    return [k.key, d ? { documentId: d.id, fileName: d.fileName, at: d.uploadedAt, by: nameOf.get(d.uploadedBy) || null } : null];
  }));
}

// The two letters of one exit: ready or not (and why), and the one already filed.
async function statusOf(record) {
  const f = await factsFor(record);
  const issued = await issuedOf(f.employee.id);
  return {
    letters: Object.values(KINDS).map((k) => ({
      key: k.key,
      title: k.title,
      ready: !blockerOf(k.key, f),
      why: blockerOf(k.key, f),
      issued: issued[k.key],
      note: k.key === 'relieving' && !blockerOf(k.key, f) && !f.fnfDone ? 'Full & final is not Processed in Payroll yet, so the letter leaves out the F&F line. Generate it again after the F&F to add it.' : null,
    })),
    signatory: { name: f.settings.signatoryName, title: f.settings.signatoryTitle },
  };
}

// -> { pdf, fileName, model } | { error, status }
async function pdfFor(record, kind) {
  if (!KINDS[kind]) return { error: 'Unknown letter.', status: 404 };
  const f = await factsFor(record);
  const why = blockerOf(kind, f);
  if (why) return { error: why, status: 409 };
  const model = modelOf(kind, f);
  return { pdf: await renderPdf(model), fileName: model.fileName, model, facts: f };
}

// Generate and file in the employee's documents. -> { status } | { error, status }
async function issue(record, kind, user) {
  const out = await pdfFor(record, kind);
  if (out.error) return out;
  const { fileDocument } = require('./internalOnboarding'); // eslint-disable-line global-require
  const doc = await fileDocument(out.facts.employee.id, KINDS[kind].docType, out.pdf, out.fileName, user ? user.id : null);
  await logAudit({ userId: user ? user.id : null, action: `${KINDS[kind].title} generated`, entity: 'Employee', entityId: out.facts.employee.id, toValue: `${out.facts.name} (${out.facts.employeeCode})` });
  if (kind === 'service') {
    // "Experience letter given" on the offboarding checklist; a step already ticked stays as it is
    try { await require('./exitChecklist').tick(record, 'letter', true, user || { name: 'HR' }); } catch { /* the letter is filed either way */ } // eslint-disable-line global-require
  }
  return { documentId: doc.id, status: await statusOf(record) };
}

module.exports = { KINDS, SETTINGS_KEY, loadSettings, saveSettings, factsFor, blockerOf, modelOf, renderPdf, statusOf, pdfFor, issue };
