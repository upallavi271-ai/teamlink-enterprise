export const UNION_TERRITORIES = ["Andaman and Nicobar Islands","Chandigarh","Dadra and Nagar Haveli and Daman and Diu","Delhi","Jammu and Kashmir","Ladakh","Lakshadweep","Puducherry"];
export const INDIA_STATE_LIST = Object.keys(INDIA_PLACES);
export const districtsOf = (state) => INDIA_PLACES[state] || [];

// ---- matching helpers ---------------------------------------------------------
// Spellings compare with spaces, dots and dashes ignored and case folded, so
// "Tamilnadu" finds "Tamil Nadu" and "hyderabad" finds "Hyderabad".
const squash = (v) => String(v || '').toLowerCase().replace(/[^a-z0-9]/g, '');

// City / state spellings the Job Portal also folds (INDIA_CITY_ALIAS) plus the
// short forms already typed in the client list ("AP").
const CITY_ALIASES = {
  bengaluru: 'Bangalore', mysuru: 'Mysore', gurugram: 'Gurgaon', bombay: 'Mumbai', calcutta: 'Kolkata', madras: 'Chennai',
  cochin: 'Kochi', trivandrum: 'Thiruvananthapuram', vizag: 'Visakhapatnam', hubballi: 'Hubli', belagavi: 'Belgaum',
  ballari: 'Bellary', mangaluru: 'Mangalore', allahabad: 'Prayagraj', shimoga: 'Shivamogga', bijapur: 'Vijayapura',
  kalaburagi: 'Gulbarga', tumakuru: 'Tumkur', chikmagalur: 'Chikkamagaluru', secunderabad: 'Hyderabad', vijayawada: 'NTR',
  delhi: 'New Delhi',
};
const STATE_ALIASES = { ap: 'Andhra Pradesh', ts: 'Telangana', tn: 'Tamil Nadu', up: 'Uttar Pradesh', mp: 'Madhya Pradesh', orissa: 'Odisha', telangan: 'Telangana' };

// The state's exact list spelling for a typed / extracted value, or ''.
export function matchState(value) {
  const k = squash(value);
  if (!k) return '';
  const alias = STATE_ALIASES[k];
  if (alias) return alias;
  return INDIA_STATE_LIST.find((s) => squash(s) === k) || '';
}

// The district's exact list spelling inside a state, or ''. A city that is the
// head of a district under another name (Bengaluru) is matched through the alias.
export function matchDistrict(state, value) {
  const list = districtsOf(state);
  const k = squash(value);
  if (!k || !list.length) return '';
  const direct = list.find((d) => squash(d) === k);
  if (direct) return direct;
  const alias = CITY_ALIASES[k];
  return alias ? (list.find((d) => squash(d) === squash(alias)) || '') : '';
}
